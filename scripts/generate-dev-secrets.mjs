#!/usr/bin/env node
// Generates throwaway secrets for LOCAL development into apps/api/.dev.vars (git-ignored).
// Never use these values in staging or production; generate those separately with
// `node scripts/generate-dev-secrets.mjs --print` and store them with `wrangler secret put`.
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps/api/.dev.vars");
const print = process.argv.includes("--print");
const force = process.argv.includes("--force");

const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const values = {
  LICENSE_KEY_PEPPER: randomBytes(32).toString("base64"),
  LEASE_SIGNING_PRIVATE_JWK: JSON.stringify(privateKey.export({ format: "jwk" })),
  MFA_ENCRYPTION_KEY: randomBytes(32).toString("base64"),
  MOCK_PAYMENT_WEBHOOK_SECRET: randomBytes(32).toString("hex"),
};
const body = Object.entries(values)
  .map(([k, v]) => `${k}=${JSON.stringify(v)}`)
  .join("\n");

if (print) {
  console.log(body);
  console.error(`\nPublic lease verification JWK (safe to embed in clients):\n${JSON.stringify(publicKey.export({ format: "jwk" }))}`);
  process.exit(0);
}
if (existsSync(target) && !force) {
  console.error(`${target} already exists. Re-run with --force to replace it (this invalidates existing dev license keys).`);
  process.exit(1);
}
writeFileSync(target, `# Generated by scripts/generate-dev-secrets.mjs - LOCAL DEVELOPMENT ONLY\n${body}\n`, { mode: 0o600 });
console.log(`Wrote ${target}`);
